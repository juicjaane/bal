"""
Automated Ecological Alert System for Blue.AI.
Monitors funded mangrove zones and sends alerts when health degrades.
Designed to be called by a scheduled job (cron / Render scheduled service).
"""
import logging
import datetime
import os
from typing import Optional
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart

logger = logging.getLogger(__name__)

ALERT_THRESHOLD_PCT = 0.10  # 10% NDVI decline triggers alert
ALERT_COOLDOWN_DAYS = 7     # Minimum days between alerts for same zone

def send_email_alert(to_email: str, subject: str, html_body: str) -> bool:
    """
    Send alert email via SMTP. Reads credentials from environment.
    SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASSWORD env vars.
    Falls back to logging if email not configured.
    """
    smtp_host = os.environ.get('SMTP_HOST')
    smtp_user = os.environ.get('SMTP_USER')
    smtp_password = os.environ.get('SMTP_PASSWORD')
    smtp_port = int(os.environ.get('SMTP_PORT', '587'))
    from_email = os.environ.get('SMTP_FROM', 'alerts@blueai.in')
    
    if not smtp_host or not smtp_user:
        logger.warning(f"Email not configured. Alert would have gone to {to_email}: {subject}")
        return False
    
    try:
        msg = MIMEMultipart('alternative')
        msg['Subject'] = subject
        msg['From'] = f"Blue.AI Alerts <{from_email}>"
        msg['To'] = to_email
        msg.attach(MIMEText(html_body, 'html'))
        
        with smtplib.SMTP(smtp_host, smtp_port) as server:
            server.starttls()
            server.login(smtp_user, smtp_password)
            server.sendmail(from_email, to_email, msg.as_string())
        
        logger.info(f"Alert sent to {to_email}: {subject}")
        return True
    except Exception as e:
        logger.error(f"Email send failed: {e}")
        return False

