def check_and_send_alerts(db, force: bool = False) -> dict:
    """
    Main function: check all NGO zones, compare NDVI, send alerts if threshold exceeded.
    Meant to be called by a scheduled job (daily/weekly).
    
    Args:
        db: Firestore client
        force: If True, ignore cooldown period (for testing)
    
    Returns: Summary dict of alerts sent/skipped
    """
    if not db:
        return {'error': 'Database not available', 'alerts_sent': 0}
    
    from .health_tracker import assess_patch_health
    
    summary = {'checked': 0, 'alerts_sent': 0, 'skipped_cooldown': 0, 'errors': 0}
    
    try:
        # Get all NGOs with their areas
        ngos = list(db.collection('users').where('type', '==', 'ngo').stream())
        
        for ngo_doc in ngos:
            ngo_data = ngo_doc.to_dict()
            area = ngo_data.get('area')
            ngo_email = ngo_data.get('email')
            
            if not area or not ngo_email:
                continue
            
            summary['checked'] += 1
            
            # Check cooldown
            if not force:
                alert_log = db.collection('alert_log').where(
                    'ngo_id', '==', ngo_doc.id
                ).where('status', '==', 'sent').order_by('sent_at', direction='DESCENDING').limit(1).stream()
                
                last_alert_docs = list(alert_log)
                if last_alert_docs:
                    last_sent = last_alert_docs[0].to_dict().get('sent_at', '')
                    if last_sent:
                        try:
                            last_dt = datetime.datetime.fromisoformat(last_sent)
                            days_since = (datetime.datetime.utcnow() - last_dt).days
                            if days_since < ALERT_COOLDOWN_DAYS:
                                summary['skipped_cooldown'] += 1
                                continue
                        except:
                            pass
            
            # Assess health
            try:
                health = assess_patch_health(area)
                
                if health.get('status') not in ('declining',) and not health.get('error'):
                    continue
                
                if health.get('error'):
                    summary['errors'] += 1
                    continue
                
                change_pct = abs(health.get('change_pct', 0))
                alert_level = 'critical' if change_pct > 20 else 'warning'
                
                alert = {
                    'ngo_id': ngo_doc.id,
                    'ngo_name': ngo_data.get('name'),
                    'area': area,
                    'alert_level': alert_level,
                    'change_pct': round(-change_pct, 1),
                    'current_ndvi': health.get('current_ndvi', 0),
                    'baseline_ndvi': health.get('baseline_ndvi', 0),
                    'detected_at': datetime.datetime.utcnow().strftime('%d %B %Y, %H:%M UTC'),
                    'status': 'sent',
                    'sent_at': datetime.datetime.utcnow().isoformat(),
                }
                
                # Alert NGO
                ngo_html = build_alert_email(alert, 'ngo')
                subject = f"Blue.AI Alert: Mangrove health declining in {area}"
                ngo_sent = send_email_alert(ngo_email, subject, ngo_html)
                
                # Alert all corporates who donated to this NGO
                corp_sent_count = 0
                donations = list(db.collection('donations').where('ngo_id', '==', ngo_doc.id).stream())
                donor_ids = set(d.to_dict().get('donor_id') for d in donations if d.to_dict().get('donor_id'))
                
                for donor_id in donor_ids:
                    corp_doc = db.collection('users').document(donor_id).get()
                    if corp_doc.exists:
                        corp_data = corp_doc.to_dict()
                        corp_email = corp_data.get('email')
                        if corp_email:
                            corp_html = build_alert_email({**alert, 'ngo_name': ngo_data.get('name')}, 'corporate')
                            send_email_alert(corp_email, subject, corp_html)
                            corp_sent_count += 1
                
                # Log alert
                db.collection('alert_log').add(alert)
                
                if ngo_sent or corp_sent_count > 0:
                    summary['alerts_sent'] += 1
                    
            except Exception as e:
                logger.error(f"Alert check failed for NGO {ngo_doc.id}: {e}")
                summary['errors'] += 1
    
    except Exception as e:
        logger.error(f"Alert batch failed: {e}")
        summary['error'] = str(e)
    
    logger.info(f"Alert sweep complete: {summary}")
    return summary
